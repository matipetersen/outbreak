#!/usr/bin/env python3
"""Build the GitHub Pages site into web/_site: the game as an installable, offline-capable phone app.

    python3 web/build.py && python3 web/pages.py

The single-file build (dist/outbreak.html) stays as it is; this adds what a real host can give it that
a data-URI page cannot: a web manifest and icons (so "Add to Home Screen" installs a fullscreen app) and a
service worker (so it keeps working with no signal once opened).
"""
import hashlib
import json
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "_site")

MANIFEST = {
    "name": "OUTBREAK",
    "short_name": "Outbreak",
    "description": "A zombie survival roguelike.",
    "id": "./",
    "start_url": "./",
    "scope": "./",
    "display": "standalone",
    "orientation": "portrait",
    "background_color": "#0d1214",
    "theme_color": "#0d1214",
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

SW = """// Generated by web/pages.py. Cache name changes with every build, so a new deploy replaces the old copy.
const CACHE = 'outbreak-%(version)s';
const FILES = ['./', 'index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png'];
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// Network first (so a deploy shows up on the next open), the cached copy when offline.
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(fetch(e.request).then((r) => {
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return r;
  }).catch(() => caches.match(e.request).then((r) => r || caches.match('index.html'))));
});
"""

HEAD = """<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="icons/icon-32.png">
<link rel="apple-touch-icon" sizes="180x180" href="icons/icon-180.png">
"""

REGISTER = """<script>
if ('serviceWorker' in navigator) window.addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
</script>
</body>"""


def main() -> None:
    src = os.path.join(HERE, "dist", "outbreak.html")
    if not os.path.exists(src):
        raise SystemExit("run python3 web/build.py first")
    html = open(src, encoding="utf8").read()
    # Put the real manifest first: browsers use the first <link rel=manifest>, and the in-page blob one is only a fallback.
    html = html.replace("<title>OUTBREAK</title>", HEAD + "<title>OUTBREAK</title>", 1)
    html = html.replace("</body>", REGISTER, 1)

    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(os.path.join(OUT, "icons"))
    with open(os.path.join(OUT, "index.html"), "w", encoding="utf8") as fh:
        fh.write(html)
    with open(os.path.join(OUT, "manifest.webmanifest"), "w", encoding="utf8") as fh:
        json.dump(MANIFEST, fh, indent=2)
    for name in ("icon-32.png", "icon-180.png", "icon-192.png", "icon-512.png"):
        shutil.copy(os.path.join(HERE, "art", "icons", name), os.path.join(OUT, "icons", name))
    version = hashlib.sha1(html.encode("utf8")).hexdigest()[:10]
    with open(os.path.join(OUT, "sw.js"), "w", encoding="utf8") as fh:
        fh.write(SW % {"version": version})
    open(os.path.join(OUT, ".nojekyll"), "w").close()
    print(f"wrote {OUT} (index.html {os.path.getsize(os.path.join(OUT, 'index.html')) / 1024:.0f} KiB, cache outbreak-{version})")


if __name__ == "__main__":
    main()
